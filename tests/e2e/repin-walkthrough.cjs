const fs=require('node:fs'),path=require('node:path');
module.exports=async({page,fixture,api,origin,output,check})=>{
 const headers={Authorization:'Bearer fixture-t008','Content-Type':'application/json'};
 const get=route=>fetch(api+route,{headers}).then(response=>response.json());
 const old=await get('/tasks/'+fixture.task+'/skill-pins');
 const before=await get('/tasks/'+fixture.task);
 check('fixture starts with approved old plan',before.plan.approved_revision===before.plan.revision);
 const file=path.join(fixture.skill_source,'SKILL.md');fs.writeFileSync(file,fs.readFileSync(file,'utf8').replace('PRIVATE SKILL INSTRUCTIONS FOR PREVIEW','NEW REVIEWED SKILL BODY'));
 const source=await get('/skill-sources/'+fixture.skill_id);
 const enabled=await fetch(api+'/skill-sources/'+fixture.skill_id+'/enable',{method:'POST',headers,body:JSON.stringify({expected_hash:source.current_hash,confirm:true})});
 check('updated source is explicitly reviewed',enabled.ok);
 await page.goto(origin);await page.getByRole('button',{name:'رد کردن',exact:true}).click();
 await page.goto(origin+'/tasks?task='+fixture.task);
 await page.locator('a[href="/customize"]').first().click();
 const button=page.getByRole('button',{name:'بازپین مهارت‌های همین کار',exact:true});await button.waitFor();
 let posts=0;page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/skill-repins'))posts++});
 await button.click();await page.getByRole('dialog').waitFor();
 check('preview does not repin',posts===0);
 await page.getByRole('button',{name:'انصراف',exact:true}).click();check('cancel preserves old pin',posts===0);
 await button.click();
 const dialog=page.getByRole('dialog');await dialog.evaluate(element=>Promise.all(element.getAnimations().map(animation=>animation.finished.catch(()=>{}))));
 await page.screenshot({path:path.join(output,'P12-repin-confirm.png')});
 await page.getByRole('button',{name:'تأیید بازپین و لغو تأیید برنامه',exact:true}).click();
 await page.getByRole('button',{name:'درخواست برنامهٔ تازه',exact:true}).waitFor();
 const updated=await get('/tasks/'+fixture.task),pins=await get('/tasks/'+fixture.task+'/skill-pins');
 check('repin changes only explicit task pin',posts===1&&pins.items.find(pin=>pin.skill_id===fixture.skill_id).hash!==old.items.find(pin=>pin.skill_id===fixture.skill_id).hash);
 check('repin withdraws approval and preserves readonly',updated.plan.approved_revision===null&&updated.read_only&&updated.status==='awaiting_plan');
 const oldApproval=await fetch(api+'/tasks/'+fixture.task+'/plan-decisions',{method:'POST',headers,body:JSON.stringify({decision:'approve',expected_revision:updated.plan.revision,idempotency_key:'reject-old-plan-after-repin'})});
 check('old plan cannot be reapproved before fresh planning',oldApproval.status===409);
 await page.screenshot({path:path.join(output,'P12-repin-done.png')});
 await page.getByRole('button',{name:'درخواست برنامهٔ تازه',exact:true}).click();
 await page.waitForURL(url=>url.pathname==='/tasks'&&url.searchParams.get('task')===fixture.task);
 let planned;
 for(let attempt=0;attempt<100;attempt++){planned=await get('/tasks/'+fixture.task);if(['awaiting_plan','failed','closed','paused'].includes(planned.status)&&planned.revision>updated.revision)break;await page.waitForTimeout(100)}
 check('explicit fresh planning returns for approval',planned.status==='awaiting_plan'&&planned.plan.approved_revision===null);
 const freshApproval=await fetch(api+'/tasks/'+fixture.task+'/plan-decisions',{method:'POST',headers,body:JSON.stringify({decision:'approve',expected_revision:planned.plan.revision,idempotency_key:'approve-new-plan-after-repin'})});
 check('fresh plan can be approved after checkpoint reload',freshApproval.ok);
 check('planning never edits original fixture',fs.readFileSync(path.join(fixture.workspace,'notes.md'),'utf8')==='Local fixture. No secrets.');
};
